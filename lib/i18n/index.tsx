export function t<K extends keyof typeof traductions.fr>(cle: K, langue: Langue = "fr"): typeof traductions.fr[K] {
  return (traductions[langue][cle] ?? traductions.fr[cle]) as typeof traductions.fr[K];
}

const CLE_LANGUE_LOCALE = "boutika_langue";

type LangueContextValue = { langue: Langue; changerLangue: (l: Langue) => Promise<void> };
const LangueContext = createContext<LangueContextValue | null>(null);

export function LangueProvider({ children }: { children: React.ReactNode }) {
  const [langue, setLangueState] = useState<Langue>(detecterLangueSysteme());

  useEffect(() => {
    chargerLangue();
  }, []);

  async function chargerLangue() {
    const langueLocale = await AsyncStorage.getItem(CLE_LANGUE_LOCALE);
    if (langueLocale && LANGUES_SUPPORTEES.includes(langueLocale as Langue)) {
      setLangueState(langueLocale as Langue);
    }

    try {
      const { data: { user } } = await supabase.auth.getUser();
      if (!user) return;

      const { data } = await supabase.from("profiles").select("langue").eq("id", user.id).single();
      if (data?.langue && LANGUES_SUPPORTEES.includes(data.langue as Langue) && !langueLocale) {
        setLangueState(data.langue as Langue);
        await AsyncStorage.setItem(CLE_LANGUE_LOCALE, data.langue);
      }
    } catch {
      // Hors ligne ou erreur réseau : pas grave, on garde la valeur locale.
    }
  }

  async function changerLangue(nouvelleLangue: Langue) {
    setLangueState(nouvelleLangue);
    await AsyncStorage.setItem(CLE_LANGUE_LOCALE, nouvelleLangue);

    try {
      const { data: { user } } = await supabase.auth.getUser();
      if (user) {
        await supabase.from("profiles").update({ langue: nouvelleLangue }).eq("id", user.id);
      }
    } catch {
      // Pas grave si ça échoue hors ligne — la prochaine synchronisation rattrapera ça.
    }
  }

  return <LangueContext.Provider value={{ langue, changerLangue }}>{children}</LangueContext.Provider>;
}

export function useLangue() {
  const ctx = useContext(LangueContext);
  if (!ctx) throw new Error("useLangue doit être utilisé dans <LangueProvider>");
  return ctx;
}